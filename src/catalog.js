export function filterProducts(items, category, query) {
  const term = query.trim().toLowerCase();
  return items.filter(
    (p) =>
      (category === "All" || p.category === category) &&
      [
        p.title,
        p.tagline,
        p.description,
        p.category,
        ...p.projects.map((v) => v.name),
      ]
        .join(" ")
        .toLowerCase()
        .includes(term),
  );
}
